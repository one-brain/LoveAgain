import React, { useState, useRef, useEffect, useCallback, useId } from 'react';
import { ChevronDownIcon, CheckIcon } from '@heroicons/react/20/solid';

export interface DropdownOption<T = string> {
  value: T;
  label: string;
  icon?: React.ReactNode;
  description?: string;
  badge?: string;
  disabled?: boolean;
}

export interface SelectDropdownProps<T = string> {
  id?: string;
  value: T;
  onChange: (value: T) => void;
  options: DropdownOption<T>[];
  label?: string;
  placeholder?: string;
  prefixIcon?: React.ReactNode;
  className?: string;
  triggerClassName?: string;
  menuClassName?: string;
  size?: 'sm' | 'md' | 'lg';
  align?: 'left' | 'right';
  disabled?: boolean;
}

export function SelectDropdown<T extends string | number>({
  id,
  value,
  onChange,
  options,
  label,
  placeholder = 'Select option...',
  prefixIcon,
  className = '',
  triggerClassName = '',
  menuClassName = '',
  size = 'md',
  align = 'left',
  disabled = false,
}: SelectDropdownProps<T>) {
  const [isOpen, setIsOpen] = useState(false);
  const [focusedIndex, setFocusedIndex] = useState<number>(-1);
  const containerRef = useRef<HTMLDivElement>(null);
  const triggerRef = useRef<HTMLButtonElement>(null);
  const menuRef = useRef<HTMLDivElement>(null);
  const autoGeneratedId = useId();
  const listboxId = id ? `${id}-listbox` : `dropdown-${autoGeneratedId}-listbox`;

  const selectedIndex = options.findIndex((opt) => opt.value === value);
  const selectedOption = selectedIndex >= 0 ? options[selectedIndex] : undefined;

  const openMenu = useCallback((initialIndex?: number) => {
    setIsOpen(true);
    setFocusedIndex(initialIndex ?? (selectedIndex >= 0 ? selectedIndex : 0));
  }, [selectedIndex]);

  const closeMenu = useCallback(() => {
    setIsOpen(false);
    setFocusedIndex(-1);
  }, []);

  // Scroll focused option into view when navigating via keyboard
  useEffect(() => {
    if (isOpen && menuRef.current && focusedIndex >= 0) {
      const optionEl = menuRef.current.children[focusedIndex] as HTMLElement | undefined;
      if (optionEl && typeof optionEl.scrollIntoView === 'function') {
        optionEl.scrollIntoView({ block: 'nearest' });
      }
    }
  }, [isOpen, focusedIndex]);

  // Close when clicked outside
  useEffect(() => {
    function handleClickOutside(event: MouseEvent) {
      if (containerRef.current && !containerRef.current.contains(event.target as Node)) {
        closeMenu();
      }
    }

    if (isOpen) {
      document.addEventListener('mousedown', handleClickOutside);
    }
    return () => {
      document.removeEventListener('mousedown', handleClickOutside);
    };
  }, [isOpen, closeMenu]);

  const sizeClasses = {
    sm: 'px-3 py-1.5 text-xs rounded-lg gap-1.5',
    md: 'px-4 py-2.5 text-sm rounded-xl gap-2',
    lg: 'px-5 py-3 text-base rounded-2xl gap-2.5',
  };

  const handleSelect = useCallback(
    (opt: DropdownOption<T>) => {
      if (opt.disabled) return;
      onChange(opt.value);
      closeMenu();
      triggerRef.current?.focus();
    },
    [onChange, closeMenu]
  );

  // Keyboard navigation
  const handleKeyDown = (e: React.KeyboardEvent) => {
    if (disabled) return;

    if (!isOpen) {
      if (e.key === 'ArrowDown' || e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        openMenu(selectedIndex >= 0 ? selectedIndex : 0);
      } else if (e.key === 'ArrowUp') {
        e.preventDefault();
        openMenu(selectedIndex >= 0 ? selectedIndex : options.length - 1);
      }
      return;
    }

    switch (e.key) {
      case 'ArrowDown': {
        e.preventDefault();
        let nextIndex = focusedIndex + 1;
        while (nextIndex < options.length && options[nextIndex]?.disabled) {
          nextIndex++;
        }
        if (nextIndex < options.length) {
          setFocusedIndex(nextIndex);
        }
        break;
      }
      case 'ArrowUp': {
        e.preventDefault();
        let prevIndex = focusedIndex - 1;
        while (prevIndex >= 0 && options[prevIndex]?.disabled) {
          prevIndex--;
        }
        if (prevIndex >= 0) {
          setFocusedIndex(prevIndex);
        }
        break;
      }
      case 'Home': {
        e.preventDefault();
        const firstEnabled = options.findIndex((opt) => !opt.disabled);
        if (firstEnabled !== -1) setFocusedIndex(firstEnabled);
        break;
      }
      case 'End': {
        e.preventDefault();
        for (let i = options.length - 1; i >= 0; i--) {
          if (!options[i]?.disabled) {
            setFocusedIndex(i);
            break;
          }
        }
        break;
      }
      case 'Enter':
      case ' ': {
        e.preventDefault();
        if (focusedIndex >= 0 && focusedIndex < options.length) {
          const opt = options[focusedIndex];
          if (opt && !opt.disabled) {
            handleSelect(opt);
          }
        }
        break;
      }
      case 'Escape': {
        e.preventDefault();
        closeMenu();
        triggerRef.current?.focus();
        break;
      }
      case 'Tab': {
        closeMenu();
        break;
      }
      default:
        break;
    }
  };

  return (
    <div
      className={`relative inline-block text-left ${className}`}
      ref={containerRef}
      onKeyDown={handleKeyDown}
    >
      {label && (
        <label
          htmlFor={id}
          className="block text-xs font-semibold text-foreground/80 mb-1.5 tracking-wide"
        >
          {label}
        </label>
      )}

      {/* Dropdown Trigger */}
      <button
        id={id}
        ref={triggerRef}
        type="button"
        disabled={disabled}
        onClick={() => (isOpen ? closeMenu() : openMenu())}
        role="combobox"
        aria-haspopup="listbox"
        aria-expanded={isOpen}
        aria-controls={listboxId}
        aria-activedescendant={
          isOpen && focusedIndex >= 0 ? `${listboxId}-option-${focusedIndex}` : undefined
        }
        className={`w-full flex items-center justify-between border transition-all duration-200 outline-none select-none font-medium ${
          sizeClasses[size]
        } ${
          isOpen
            ? 'border-accent ring-2 ring-accent/25 bg-card text-foreground shadow-md'
            : 'border-border/80 bg-card hover:bg-muted/70 text-foreground shadow-xs hover:border-border'
        } ${disabled ? 'opacity-50 cursor-not-allowed' : 'cursor-pointer'} ${triggerClassName}`}
      >
        <span className="flex items-center gap-2 truncate">
          {prefixIcon && <span className="text-muted-foreground flex-shrink-0">{prefixIcon}</span>}
          {selectedOption?.icon && (
            <span className="text-accent flex-shrink-0">{selectedOption.icon}</span>
          )}
          <span className="truncate">{selectedOption ? selectedOption.label : placeholder}</span>
        </span>

        <ChevronDownIcon
          className={`w-4 h-4 text-muted-foreground ml-2 transition-transform duration-200 flex-shrink-0 ${
            isOpen ? 'rotate-180 text-accent' : ''
          }`}
        />
      </button>

      {/* Dropdown Menu Popover */}
      {isOpen && (
        <div
          id={listboxId}
          ref={menuRef}
          role="listbox"
          tabIndex={-1}
          aria-label={label || placeholder}
          className={`absolute z-50 mt-2 min-w-[200px] max-h-72 overflow-y-auto rounded-2xl bg-popover/95 text-popover-foreground border border-border/90 shadow-2xl backdrop-blur-md p-1.5 focus:outline-none animate-in fade-in-0 zoom-in-95 duration-150 ${
            align === 'right' ? 'right-0' : 'left-0'
          } ${menuClassName}`}
        >
          {options.map((opt, idx) => {
            const isSelected = opt.value === value;
            const isFocused = idx === focusedIndex;
            return (
              <div
                key={String(opt.value)}
                id={`${listboxId}-option-${idx}`}
                role="option"
                aria-selected={isSelected}
                aria-disabled={opt.disabled}
                onClick={() => handleSelect(opt)}
                onMouseEnter={() => {
                  if (!opt.disabled) setFocusedIndex(idx);
                }}
                className={`flex items-center justify-between px-3 py-2 rounded-xl text-xs sm:text-sm font-medium transition-colors cursor-pointer select-none ${
                  opt.disabled
                    ? 'opacity-40 cursor-not-allowed'
                    : isSelected
                    ? 'bg-accent/15 text-accent font-semibold'
                    : isFocused
                    ? 'bg-muted text-foreground'
                    : 'text-foreground/90 hover:bg-muted hover:text-foreground'
                }`}
              >
                <div className="flex items-center gap-2.5 truncate">
                  {opt.icon && (
                    <span
                      className={`flex-shrink-0 ${
                        isSelected ? 'text-accent' : 'text-muted-foreground'
                      }`}
                    >
                      {opt.icon}
                    </span>
                  )}
                  <div className="truncate">
                    <div className="truncate">{opt.label}</div>
                    {opt.description && (
                      <div className="text-[11px] text-muted-foreground font-normal truncate mt-0.5">
                        {opt.description}
                      </div>
                    )}
                  </div>
                </div>

                <div className="flex items-center gap-2 ml-2 flex-shrink-0">
                  {opt.badge && (
                    <span className="px-1.5 py-0.5 rounded-md text-[10px] font-semibold bg-muted text-muted-foreground uppercase tracking-wider">
                      {opt.badge}
                    </span>
                  )}
                  {isSelected && (
                    <CheckIcon className="w-4 h-4 text-accent animate-in fade-in duration-100" />
                  )}
                </div>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}
